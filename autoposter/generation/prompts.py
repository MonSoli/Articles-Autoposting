"""Промпты пайплайна. Вся база знаний подмешивается сюда."""

from __future__ import annotations

import functools
from pathlib import Path

KNOWLEDGE_DIR = Path(__file__).resolve().parent.parent / "knowledge"


@functools.lru_cache(maxsize=None)
def knowledge(*names: str) -> str:
    """Склеивает файлы базы знаний по префиксу имени."""
    parts: list[str] = []
    for name in names:
        matches = sorted(KNOWLEDGE_DIR.glob(f"*{name}*.md"))
        for path in matches:
            parts.append(f"<knowledge file=\"{path.name}\">\n{path.read_text(encoding='utf-8')}\n</knowledge>")
    return "\n\n".join(parts)


