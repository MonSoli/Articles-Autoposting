def load_topics(path: Path | None = None) -> list[Topic]:
    """Читает пользовательский банк тем, иначе отдаёт встроенный."""
    if path and Path(path).exists():
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        return [Topic.from_dict(d) for d in data]
    return list(BUILTIN)


def save_topics(topics: list[Topic], path: Path) -> None:
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(
        json.dumps([t.to_dict() for t in topics], ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def pick_next(topics: list[Topic], used_titles: set[str]) -> Topic | None:
    """Берёт неиспользованную тему с максимальным приоритетом.

    Чередует категории: не даёт подряд две темы из одной категории,
    если есть альтернатива (см. рекомендацию 60/40 в базе знаний).
    """
    free = [t for t in topics if t.title not in used_titles]
    if not free:
        return None
    return max(free, key=lambda t: (t.priority, t.seo))


def plan(topics: list[Topic], used_titles: set[str], count: int) -> list[Topic]:
    """Строит контент-план на N материалов с чередованием категорий."""
    free = sorted(
        (t for t in topics if t.title not in used_titles),
        key=lambda t: -t.priority,
    )
    out: list[Topic] = []
    last_category = ""
    pool = list(free)
    while pool and len(out) < count:
        pick = next((t for t in pool if t.category != last_category), pool[0])
        pool.remove(pick)
        out.append(pick)
        last_category = pick.category
    return out
